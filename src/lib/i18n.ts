const dicts: Record<Lang, Dict> = { ko, en, ja, cn, tw };

export function getDict(lang: Lang): Dict {
  return dicts[lang] ?? ko;
}

export function tr(lang: Lang, key: Keys, vars?: Record<string, string | number>): string {
  const s = getDict(lang)[key];
  return vars ? fmt(s, vars) : s;
}
